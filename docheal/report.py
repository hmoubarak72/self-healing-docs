"""Markdown rendering for the PR comment, fix-PR body and job summary."""

from __future__ import annotations

import difflib

from .pipeline import CheckReport

MARKER = "<!-- docheal-report -->"


def _link(repo: str | None, sha: str | None, path: str, start: int, end: int) -> str:
    if repo and sha:
        return f"[`{path}` L{start}-L{end}](https://github.com/{repo}/blob/{sha}/{path}#L{start}-L{end})"
    return f"`{path}` L{start}-L{end}"


def _diff(a: str, b: str) -> str:
    d = difflib.unified_diff(a.splitlines(), b.splitlines(), "current", "suggested", lineterm="", n=1)
    return "\n".join(list(d)[2:]) or "(no textual change)"


def headline(report: CheckReport, fix_pr: str | None = None) -> str:
    n_ok, n_fix, n_flag = len(report.accurate), len(report.auto_fixed), len(report.flagged)
    fix_ref = f" (see {fix_pr})" if fix_pr and n_fix else ""
    return (f"**Doc Check Results:** {n_ok} section{'s' if n_ok != 1 else ''} verified accurate, "
            f"{n_fix} auto-fixed{fix_ref}, {n_flag} flagged for review.")


def render_comment(report: CheckReport, repo: str | None = None, sha: str | None = None,
                   fix_pr: str | None = None) -> str:
    lines = [MARKER, "## 📚 DocHeal — Doc Check Results", "", headline(report, fix_pr), ""]
    d = report.diff
    lines.append(f"<sub>Engine: `{report.engine}` · {len(d.files)} changed files · "
                 f"{len(d.changes)} meaningful code changes · {len(d.skipped)} cosmetic/docstring-only changes "
                 f"ignored · {len(report.suspects)} doc sections checked</sub>")
    lines.append("")
    if not d.changes:
        lines.append("✅ No documentation-relevant code changes detected (test, comment, and whitespace-only "
                     "changes are ignored).")
        return "\n".join(lines)

    if report.auto_fixed:
        lines += ["### 🔧 Auto-fixed (high confidence)", "", "| Section | Confidence | What changed |",
                  "|---|---|---|"]
        for c in report.auto_fixed:
            lines.append(f"| {_link(repo, sha, c.path, c.start_line, c.end_line)} — {c.heading_path} | "
                         f"{c.confidence:.0%} | {c.explanation[:220].replace('|', '/')} |")
        lines.append("")
    if report.flagged:
        lines += ["### 🔎 Needs human review", ""]
        for c in report.flagged:
            lines.append(f"- **{c.heading_path}** — {_link(repo, sha, c.path, c.start_line, c.end_line)} "
                         f"(confidence {c.confidence:.0%})")
            lines.append(f"  - {c.explanation}")
            if not c.validation_passed:
                lines.append(f"  - Quality gate: {c.validation_notes}")
            lines += ["", "  <details><summary>Suggested draft</summary>", "", "  ```diff"]
            lines += ["  " + l for l in _diff(c.original, c.corrected).splitlines()]
            lines += ["  ```", "  </details>", ""]
    if report.accurate:
        lines += ["<details><summary>✅ Verified accurate</summary>", ""]
        sec = {s.section.id: s.section for s in report.suspects}
        for v in report.accurate:
            s = sec.get(v.doc_id)
            where = _link(repo, sha, s.path, s.start_line, s.end_line) if s else v.doc_id
            lines.append(f"- {s.heading_path if s else v.doc_id} — {where}")
        lines += ["", "</details>"]
    lines += ["", "<sub>🤖 Generated by DocHeal — self-healing technical documentation.</sub>"]
    return "\n".join(lines)


def render_fix_pr_body(report: CheckReport, source_pr: int | None) -> str:
    lines = ["## 📚 DocHeal: automated documentation fixes", ""]
    if source_pr:
        lines.append(f"Code changes in #{source_pr} made the following documentation sections inaccurate. "
                     "This PR applies targeted, validated corrections.")
    lines.append("")
    for c in report.auto_fixed:
        lines += [f"### `{c.path}` — {c.heading_path}", "", f"**Why:** {c.explanation}", "",
                  f"**Confidence:** {c.confidence:.0%} · **Quality gate:** {c.validation_notes}", "",
                  "```diff", _diff(c.original, c.corrected), "```", ""]
    lines.append("<sub>Only stale statements were rewritten; accurate content is preserved verbatim.</sub>")
    return "\n".join(lines)
